def make_para(pPr_clone, text, bold=False, italic=False, sz=14):
    p = OxmlElement('w:p')
    if pPr_clone is not None:
        p.append(copy.deepcopy(pPr_clone))
    if text:
        r   = OxmlElement('w:r')
        rPr = OxmlElement('w:rPr')
        fonts = OxmlElement('w:rFonts')
        for a in ('w:ascii', 'w:hAnsi', 'w:cs'):
            fonts.set(qn(a), 'Times New Roman')
        rPr.append(fonts)
        if bold:
            rPr.append(OxmlElement('w:b'))
        if italic:
            rPr.append(OxmlElement('w:i'))
        szEl = OxmlElement('w:sz');   szEl.set(qn('w:val'), str(sz * 2))
        szCsEl = OxmlElement('w:szCs'); szCsEl.set(qn('w:val'), str(sz * 2))
        rPr.append(szEl); rPr.append(szCsEl)
        r.append(rPr)
        t = OxmlElement('w:t')
        t.text = text
        t.set('{http://www.w3.org/XML/1998/namespace}space', 'preserve')
        r.append(t)
        p.append(r)
    return p


def empty():
    return make_para(None, '')


def separator():
    p = OxmlElement('w:p')
    pPr = OxmlElement('w:pPr')
    pBdr = OxmlElement('w:pBdr')
    bot = OxmlElement('w:bottom')
    bot.set(qn('w:val'), 'single')
    bot.set(qn('w:sz'), '6')
    bot.set(qn('w:space'), '1')
    bot.set(qn('w:color'), '000000')
    pBdr.append(bot)
    pPr.append(pBdr)
    p.append(pPr)
    return p


def annex_block(header, items, sz_h=12, sz_i=12):
    ins(make_para(ref_ann_h, header, italic=True, sz=sz_h))
    for i, item in enumerate(items, 1):
        ins(make_para(ref_ann_i, f"{i}) {item}", italic=True, sz=sz_i))


