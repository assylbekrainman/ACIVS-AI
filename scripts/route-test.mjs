/**
 * Проверка роутера: какие скиллы подберутся на типовые команды.
 *   npm run skills:test            — прогон встроенных примеров
 *   npm run skills:test -- "текст" — своя фраза
 */
import { matchSkills, loadSkills } from '../bridge/skills.mjs'

const custom = process.argv.slice(2).join(' ')
const samples = custom
  ? [custom]
  : [
      'проверь бюджет: ФОТ и аренда в пределах лимита?',
      'найди красные флаги в отчёте грантополучателя',
      'сделай СЗ на транш',
      'нужна эскроу-расписка на зарплату по проекту',
      'письмо в Комитет науки на рассмотрение ННС',
      'проверь проект договора гранта перед подписанием',
      'проверь контрагента по БИН',
      'какой лимит по ФОТ в конкурсной документации',
      'справка о статусе проекта',
      'ежемесячный мониторинг табелей',
      'переведи уведомление на казахский',
    ]

console.log(`Скиллов загружено: ${loadSkills().length}\n`)
for (const t of samples) {
  const m = matchSkills(t, 3)
  console.log(`«${t}»`)
  console.log(
    m.length
      ? m.map((x) => `   → ${x.skill.name}  [${x.hits.slice(0, 3).join(' | ')}]`).join('\n')
      : '   → совпадений нет (агент возьмёт навигатор)',
  )
}
